//! ADIF datagram parser with per-record error recovery (research R6).

use super::AdifRecord;
use crate::errors::Error;

/// Parses every record in `data`.
///
/// A malformed record is reported in the error list and skipped; parsing resumes at the next
/// `<EOR>`, so the valid records around it are still returned (SC-006). Text before the first
/// tag is ignored, and everything up to `<EOH>` is treated as header and dropped.
pub fn parse_datagram(data: &[u8]) -> (Vec<AdifRecord>, Vec<Error>) {
    let mut records = Vec::new();
    let mut errors = Vec::new();
    let mut current = AdifRecord::new();
    let mut index = 0usize;
    let mut pos = 0usize;

    while let Some(open) = find_byte(data, b'<', pos) {
        let Some(close) = find_byte(data, b'>', open + 1) else {
            if !current.is_empty() {
                errors.push(adif_error(index, "unterminated tag"));
                current = AdifRecord::new();
            }
            break;
        };
        let tag = &data[open + 1..close];
        pos = close + 1;

        if tag.eq_ignore_ascii_case(b"EOH") {
            current = AdifRecord::new();
            continue;
        }
        if tag.eq_ignore_ascii_case(b"EOR") {
            if !current.is_empty() {
                records.push(std::mem::take(&mut current));
            }
            index += 1;
            continue;
        }

        match read_field(data, tag, pos) {
            Ok((name, value, next)) => {
                current.set(&name, value);
                pos = next;
            }
            Err(message) => {
                errors.push(adif_error(index, &message));
                current = AdifRecord::new();
                index += 1;
                pos = skip_past_eor(data, pos);
            }
        }
    }

    if current.get_non_empty("CALL").is_some() {
        records.push(current);
    }
    (records, errors)
}

fn read_field(
    data: &[u8],
    tag: &[u8],
    value_start: usize,
) -> Result<(String, String, usize), String> {
    let tag = std::str::from_utf8(tag).map_err(|_| "tag is not valid UTF-8".to_string())?;
    let mut parts = tag.splitn(3, ':');
    let name = parts.next().unwrap_or_default().trim();
    let length = parts
        .next()
        .ok_or_else(|| format!("tag <{tag}> has no length"))?
        .trim();
    if name.is_empty() || !name.bytes().all(|b| b.is_ascii_graphic()) {
        return Err(format!("invalid field name in <{tag}>"));
    }
    let length: usize = length
        .parse()
        .map_err(|_| format!("invalid length in <{tag}>"))?;
    let end = value_start
        .checked_add(length)
        .filter(|end| *end <= data.len())
        .ok_or_else(|| format!("value of {name} runs past the end of the datagram"))?;
    let value = std::str::from_utf8(&data[value_start..end])
        .map_err(|_| format!("value of {name} is not valid UTF-8"))?;
    Ok((name.to_string(), value.to_string(), end))
}

fn find_byte(data: &[u8], byte: u8, from: usize) -> Option<usize> {
    data.get(from..)?
        .iter()
        .position(|b| *b == byte)
        .map(|i| i + from)
}

fn skip_past_eor(data: &[u8], from: usize) -> usize {
    let mut pos = from;
    while let Some(open) = find_byte(data, b'<', pos) {
        let end = open + 5;
        if end <= data.len() && data[open..end].eq_ignore_ascii_case(b"<EOR>") {
            return end;
        }
        pos = open + 1;
    }
    data.len()
}

fn adif_error(record: usize, message: &str) -> Error {
    Error::Adif {
        record,
        message: message.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(s: &str) -> (Vec<AdifRecord>, Vec<Error>) {
        parse_datagram(s.as_bytes())
    }

    #[test]
    fn parses_one_record() {
        let (records, errors) = parse("<CALL:5>DL5AB <QSO_DATE:8>20261008 <TIME_ON:6>150404 <EOR>");
        assert!(errors.is_empty());
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("CALL"), Some("DL5AB"));
        assert_eq!(records[0].get("QSO_DATE"), Some("20261008"));
        assert_eq!(records[0].get("TIME_ON"), Some("150404"));
    }

    #[test]
    fn skips_header_before_eoh() {
        let (records, errors) = parse(
            "Generated by test\n<ADIF_VER:5>3.1.4 <PROGRAMID:4>TEST <EOH>\n<CALL:4>K1AA <EOR>",
        );
        assert!(errors.is_empty());
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("ADIF_VER"), None);
        assert_eq!(records[0].get("PROGRAMID"), None);
        assert_eq!(records[0].get("CALL"), Some("K1AA"));
    }

    #[test]
    fn header_starting_with_a_tag_is_skipped_too() {
        let (records, _) = parse("<ADIF_VER:5>3.1.4 <EOH><CALL:4>K1AA <EOR>");
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("ADIF_VER"), None);
    }

    #[test]
    fn three_records_in_one_datagram() {
        let (records, errors) = parse("<CALL:3>K1A <EOR><CALL:3>K2B <EOR>\n<CALL:3>K3C <EOR>");
        assert!(errors.is_empty());
        let calls: Vec<_> = records.iter().map(|r| r.get("CALL").unwrap()).collect();
        assert_eq!(calls, ["K1A", "K2B", "K3C"]);
    }

    #[test]
    fn field_names_are_case_insensitive_and_stored_uppercase() {
        let (records, _) = parse("<call:4>K1AA <Qso_Date:8>20261008 <eor>");
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("CALL"), Some("K1AA"));
        assert_eq!(records[0].get("call"), Some("K1AA"));
        assert_eq!(records[0].get("QSO_DATE"), Some("20261008"));
    }

    #[test]
    fn accepts_type_indicator() {
        let (records, errors) = parse("<FREQ:5:N>7.012 <CALL:4>K1AA <EOR>");
        assert!(errors.is_empty());
        assert_eq!(records[0].get("FREQ"), Some("7.012"));
    }

    #[test]
    fn length_counts_utf8_bytes() {
        let (records, errors) = parse("<NAME:7>Jürgen <CALL:4>DL1A <EOR>");
        assert!(errors.is_empty(), "{errors:?}");
        assert_eq!(records[0].get("NAME"), Some("Jürgen"));
    }

    #[test]
    fn text_before_first_tag_is_ignored() {
        let (records, _) = parse("garbage text <CALL:4>K1AA <EOR>");
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("CALL"), Some("K1AA"));
    }

    #[test]
    fn trailing_record_without_eor_is_kept_when_it_has_call() {
        let (records, _) = parse("<CALL:3>K1A <EOR><CALL:3>K2B <BAND:3>20m");
        assert_eq!(records.len(), 2);
        assert_eq!(records[1].get("BAND"), Some("20m"));
    }

    #[test]
    fn trailing_fields_without_call_are_dropped() {
        let (records, _) = parse("<CALL:3>K1A <EOR><BAND:3>20m");
        assert_eq!(records.len(), 1);
    }

    #[test]
    fn malformed_record_is_skipped_and_neighbours_survive() {
        let (records, errors) =
            parse("<CALL:3>K1A <EOR><CALL:X>K2B <EOR><CALL:3>K3C <EOR><CALL:99>K4D <EOR>");
        let calls: Vec<_> = records.iter().map(|r| r.get("CALL").unwrap()).collect();
        assert_eq!(calls, ["K1A", "K3C"]);
        assert_eq!(errors.len(), 2);
        assert!(matches!(errors[0], Error::Adif { record: 1, .. }));
        assert!(matches!(errors[1], Error::Adif { record: 3, .. }));
    }

    #[test]
    fn negative_length_is_an_error() {
        let (records, errors) = parse("<CALL:-1>K1A <EOR><CALL:3>K2B <EOR>");
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("CALL"), Some("K2B"));
        assert_eq!(errors.len(), 1);
    }

    #[test]
    fn invalid_utf8_value_is_an_error() {
        let mut data = b"<NAME:2>".to_vec();
        data.extend_from_slice(&[0xff, 0xfe]);
        data.extend_from_slice(b" <CALL:3>K1A <EOR><CALL:3>K2B <EOR>");
        let (records, errors) = parse_datagram(&data);
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].get("CALL"), Some("K2B"));
        assert_eq!(errors.len(), 1);
    }

    #[test]
    fn empty_input_gives_nothing() {
        let (records, errors) = parse("");
        assert!(records.is_empty());
        assert!(errors.is_empty());
    }

    #[test]
    fn zero_length_field_is_empty_value() {
        let (records, errors) = parse("<CALL:3>K1A <COMMENT:0><EOR>");
        assert!(errors.is_empty());
        assert_eq!(records[0].get("COMMENT"), Some(""));
    }
}
