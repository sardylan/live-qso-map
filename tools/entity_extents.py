#!/usr/bin/env python3
"""Generate src/web/entity_extents.json from Natural Earth (feature 004, research R2).

Dev-only and standard library only: the output is committed and embedded in the binary, so
nothing is downloaded at runtime.

    python3 tools/entity_extents.py --cty cty.dat --mapping tools/entity_extents.toml \
        --out src/web/entity_extents.json

The mapping (TOML) has one table per cty.dat primary prefix (without the WAE `*`):

    [IS]                      # Sardinia
    admin1 = ["IT-88"]

Selector keys:
  admin0          SU_A3 codes from ne_10m_admin_0_map_subunits
  admin1          iso_3166_2 codes from ne_10m_admin_1_states_provinces
  admin1_of       every admin-1 unit of these adm0_a3 countries
  exclude_admin1  iso_3166_2 codes removed from the selection
  clip            [w, s, e, n]: only vertices inside this box count
  note            free text

Entities Natural Earth cannot represent are listed in an `[unmapped]` table, prefix = reason.
The script fails when a cty.dat entity is neither mapped nor listed.
"""

import argparse
import json
import math
import os
import sys
import tomllib
import urllib.request

NE_VERSION = "v5.1.2"
NE_BASE = f"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{NE_VERSION}/geojson/"
SUBUNITS = "ne_10m_admin_0_map_subunits.geojson"
ADMIN1 = "ne_10m_admin_1_states_provinces.geojson"
SOURCE = f"Natural Earth {NE_VERSION} (public domain), generated by tools/entity_extents.py"
SELECTOR_KEYS = {"admin0", "admin1", "admin1_of", "exclude_admin1", "clip", "note"}


def cty_prefixes(text):
    """Primary prefixes of every entity in a cty.dat file, in file order, without `*`."""
    prefixes = []
    for line in text.splitlines():
        if not line.strip() or line[0].isspace():
            continue
        fields = [f.strip() for f in line.split(":")]
        if len(fields) >= 8 and fields[7]:
            prefixes.append(fields[7].lstrip("*"))
    return prefixes


def min_lon_span(lons):
    """(west, east) of the shortest longitude interval holding every value (largest-gap method).

    `west > east` means the interval crosses the antimeridian.
    """
    values = sorted(set(lons))
    if len(values) == 1:
        return values[0], values[0]
    gaps = [(values[i + 1] - values[i], i) for i in range(len(values) - 1)]
    wrap_gap = values[0] + 360.0 - values[-1]
    biggest, at = max(gaps)
    if wrap_gap >= biggest:
        return values[0], values[-1]
    return values[at + 1], values[at]


def _rings(geometry):
    if geometry is None:
        return
    if geometry["type"] == "Polygon":
        yield from geometry["coordinates"]
    elif geometry["type"] == "MultiPolygon":
        for polygon in geometry["coordinates"]:
            yield from polygon


def _inside(clip, lon, lat):
    w, s, e, n = clip
    in_lon = w <= lon <= e if w <= e else (lon >= w or lon <= e)
    return in_lon and s <= lat <= n


def select(subunits, admin1, selector):
    """The (lon, lat) vertices selected by one mapping entry."""
    unknown = set(selector) - SELECTOR_KEYS
    if unknown:
        raise ValueError(f"unknown selector keys: {sorted(unknown)}")
    excluded = set(selector.get("exclude_admin1", []))
    chosen = []
    codes0 = set(selector.get("admin0", []))
    chosen += [f for f in subunits if f["properties"].get("SU_A3") in codes0]
    codes1 = set(selector.get("admin1", []))
    countries = set(selector.get("admin1_of", []))
    chosen += [
        f
        for f in admin1
        if f["properties"].get("iso_3166_2") not in excluded
        and (f["properties"].get("iso_3166_2") in codes1 or f["properties"].get("adm0_a3") in countries)
    ]
    clip = selector.get("clip")
    points = []
    for f in chosen:
        for ring in _rings(f["geometry"]):
            for lon, lat, *_ in ring:
                if clip is None or _inside(clip, lon, lat):
                    points.append((lon, lat))
    return points


def extent(points):
    """[w, s, e, n] of the vertices, or None when there are none."""
    if not points:
        return None
    w, e = min_lon_span([lon for lon, _ in points])
    lats = [lat for _, lat in points]
    return [w, min(lats), e, max(lats)]


def outward(box):
    """Rounds a box to 2 decimals without shrinking it, and keeps south < north.

    Tiny entities (Vatican City) would otherwise collapse to a point.
    """
    w, s, e, n = box
    w, s = math.floor(w * 100) / 100, math.floor(s * 100) / 100
    e, n = math.ceil(e * 100) / 100, math.ceil(n * 100) / 100
    if n <= s:
        n = round(s + 0.01, 2)
    return [max(w, -180.0), max(s, -90.0), min(e, 180.0), min(n, 90.0)]


def render(extents):
    """Deterministic JSON: sorted keys, 2 decimals rounded outward, no timestamp."""
    rows = [f"  {json.dumps(k)}: {json.dumps(outward(extents[k]))}" for k in sorted(extents)]
    return '{\n "source": ' + json.dumps(SOURCE) + ',\n "extents": {\n' + ",\n".join(rows) + "\n }\n}\n"


def check_coverage(prefixes, mapping, unmapped):
    missing = [p for p in prefixes if p not in mapping and p not in unmapped]
    if missing:
        raise ValueError(f"entities neither mapped nor listed under [unmapped]: {', '.join(missing)}")


def _download(cache, name):
    os.makedirs(cache, exist_ok=True)
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        print(f"downloading {name} …", file=sys.stderr)
        urllib.request.urlretrieve(NE_BASE + name, path + ".part")
        os.replace(path + ".part", path)
    with open(path, encoding="utf-8") as f:
        return json.load(f)["features"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cty", required=True)
    parser.add_argument("--mapping", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--cache", default=".cache/naturalearth")
    args = parser.parse_args(argv)

    with open(args.cty, encoding="latin-1") as f:
        prefixes = cty_prefixes(f.read())
    with open(args.mapping, "rb") as f:
        mapping = tomllib.load(f)
    unmapped = mapping.pop("unmapped", {})
    check_coverage(prefixes, mapping, unmapped)

    subunits = _download(args.cache, SUBUNITS)
    admin1 = _download(args.cache, ADMIN1)
    extents = {}
    empty = []
    for prefix, selector in mapping.items():
        box = extent(select(subunits, admin1, selector))
        if box is None:
            empty.append(prefix)
        else:
            extents[prefix] = box
    if empty:
        raise SystemExit(f"selectors matched nothing for: {', '.join(sorted(empty))}")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(render(extents))
    mapped = sum(1 for p in prefixes if p in extents)
    print(f"{mapped}/{len(prefixes)} entities mapped ({100 * mapped / len(prefixes):.1f} %); "
          f"{len(unmapped)} listed as unmapped", file=sys.stderr)


if __name__ == "__main__":
    main()
